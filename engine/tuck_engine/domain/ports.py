"""Ports owned by the core. Implementations live outside this package."""

from __future__ import annotations
from typing import Protocol, Callable, ContextManager, Any
from pathlib import Path
from .model import Meeting, TranscriptSegment


class MeetingRepository(Protocol):
    def get(self, meeting_id: str) -> Meeting: ...
    def list(self) -> list[Meeting]: ...
    def save(self, meeting: Meeting) -> None: ...
    def delete(self, meeting: Meeting) -> None: ...


class EvidenceRepository(Protocol):
    def append(self, segment: TranscriptSegment) -> bool: ...
    def segments(self, meeting_id: str) -> list[dict]: ...
    def speakers(self, meeting_id: str) -> list[dict]: ...
    def rename_speaker(self, meeting_id: str, speaker_id: str, name: str) -> None: ...
    def messages(self, meeting_id: str) -> list[dict]: ...
    def add_message(self, meeting_id: str, message: dict) -> None: ...
    def bookmarks(self, meeting_id: str) -> list[dict]: ...
    def add_bookmark(self, meeting_id: str, bookmark: dict) -> None: ...
    def remove_bookmark(self, meeting_id: str, bookmark_id: str) -> None: ...


class SettingsRepository(Protocol):
    def get(self) -> dict: ...
    def save(self, values: dict) -> None: ...


class UnitOfWork(Protocol):
    meetings: MeetingRepository
    evidence: EvidenceRepository
    settings: SettingsRepository

    def __enter__(self) -> UnitOfWork: ...
    def __exit__(self, *args: Any) -> None: ...
    def commit(self) -> None: ...


class RecordingPort(Protocol):
    def status(self) -> dict: ...
    def start(
        self,
        meeting_id: str,
        on_segment: Callable[[dict], None],
        system_audio: bool,
        microphone: bool,
        threads: int = 2,
        keep_audio: bool = True,
    ) -> None: ...
    def pause(self) -> None: ...
    def resume(self) -> None: ...
    def stop(self) -> float: ...
    def shutdown(self) -> None: ...
    def install_model(self, kind: str) -> dict: ...
    def unload(self) -> None: ...
    def import_file(
        self,
        path: str,
        meeting_id: str,
        on_segment: Callable[[dict], None],
        threads: int = 2,
    ) -> float: ...


class IntelligencePort(Protocol):
    def models(self, settings: dict) -> list[dict]: ...
    def complete(
        self,
        settings: dict,
        system: str,
        messages: list[dict],
        on_delta: Callable[[str], None],
    ) -> str: ...


class PublicationPort(Protocol):
    def publish(self, target: str, meeting: dict) -> str: ...


class SecretPort(Protocol):
    def get(self, kind: str) -> str | None: ...
    def set(self, kind: str, value: str) -> None: ...
    def delete(self, kind: str) -> None: ...


class AccountPort(Protocol):
    def accounts(self) -> list[dict]: ...
    def sign_in(self, account_id: str | None = None) -> list[dict]: ...
    def select(self, account_id: str) -> list[dict]: ...
    def sign_out(self, account_id: str) -> dict: ...


class AudioArchivePort(Protocol):
    def remove(self, meeting_id: str) -> None: ...
    def export(self, path: str, content: str) -> None: ...
